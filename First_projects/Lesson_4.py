# Определение и вывод типов данных

a = 12; # целочисленный тип данных (целое число)
b = 'слово'; # строковый тип данных (строка)
c = False; # логический тип данных
d = 1.25; # тип данных с плавающей точкой
n = None; # тип данных None

a_type = type(a);
b_type = type(b);
c_type = type(c);
d_type = type(d);
n_type = type(n);

print(a_type)
print(b_type)
print(c_type)
print(d_type)
print(n_type)